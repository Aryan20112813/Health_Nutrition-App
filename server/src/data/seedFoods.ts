/**
 * Seeds the food collection if it is currently empty.
 */
export async function seedFoodCatalogIfNeeded(): Promise<number> {
  const count = await Food.countDocuments();
  if (count === 0) {
    await Food.insertMany(SEED_FOODS_CATALOG);
    console.log(`[Database] Initialized ${SEED_FOODS_CATALOG.length} items in curated food catalog.`);
    return SEED_FOODS_CATALOG.length;
  }
  return count;
}
